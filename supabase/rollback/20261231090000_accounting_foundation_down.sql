-- Every accounting_* function of the migration (public RPCs, private helpers and trigger functions).
-- None existed before 20261231090000.
do $$
declare
  r record;
begin
  for r in
    select p.oid::regprocedure as fn
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'private') and p.proname like 'accounting\_%'
  loop
    execute format('drop function if exists %s', r.fn);
  end loop;
end;
$$;

