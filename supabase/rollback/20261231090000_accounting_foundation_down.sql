-- Rollback of 20261231090000_accounting_foundation.
--
-- Run 20261231090100_accounting_auto_posting_down.sql first.
--
-- Drops the accounting tables, functions, guards and the 12 accounting permissions, and restores the
-- ERP reset registries of 20261228090000 / 20261118090000. No business table (invoices, receipts,
-- notes, goods receipts, supplier payments, parties, inventory) was changed by the migration, so
-- nothing is restored there. audit_logs entries written by accounting stay (append-only).
--
-- Refused while any accounting record exists (vouchers, opening balances, posting events, or a set-up
-- company), because dropping the tables deletes the books. To roll back anyway, export the books, then
--   set app.accounting_rollback_force = 'on';
-- in the same session.

do $$
begin
  if coalesce(current_setting('app.accounting_rollback_force', true), '') <> 'on' and to_regclass('public.accounting_settings') is not null
     and (exists (select 1 from public.accounting_settings) or exists (select 1 from public.accounting_vouchers)
          or exists (select 1 from public.accounting_posting_events) or exists (select 1 from public.accounting_opening_balance_batches)) then
    raise exception 'Accounting data exists. Export the books, then set app.accounting_rollback_force = on to roll back.';
  end if;
end;
$$;

