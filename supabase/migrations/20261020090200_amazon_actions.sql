-- -----------------------------------------------------------------------------
-- Ad change requests
-- -----------------------------------------------------------------------------
-- Checks a proposed value against the company limits; returns a problem or null.
create or replace function private.amazon_change_problem(p_company uuid, p_type text, p_old jsonb, p_new jsonb)
returns text language plpgsql stable security definer set search_path = '' as $$
declare s public.amazon_settings; v_old numeric; v_new numeric;
begin
  select * into s from public.amazon_settings where company_id = p_company;
  if p_type = 'CAMPAIGN_BUDGET' then
    v_new := (p_new ->> 'daily_budget')::numeric; v_old := (p_old ->> 'daily_budget')::numeric;
    if v_new is null or v_new <= 0 then return 'The new daily budget must be greater than zero.'; end if;
    if s.max_daily_budget is not null and v_new > s.max_daily_budget then return format('The daily budget %s exceeds the configured maximum of %s.', v_new, s.max_daily_budget); end if;
    if s.max_monthly_budget is not null and (select coalesce(sum(c.daily_budget), 0) from public.amazon_campaigns c
        where c.company_id = p_company and c.state = 'ENABLED' and not c.is_demo and c.campaign_id <> coalesce(p_new ->> 'campaign_id', '')) * 30.4 + v_new * 30.4 > s.max_monthly_budget then
      return format('All enabled campaigns at their daily budgets would exceed the monthly maximum of %s.', s.max_monthly_budget);
    end if;
    if v_old > 0 and abs(v_new - v_old) / v_old * 100 > s.max_budget_change_pct then
      return format('The change of %s%% is larger than the allowed %s%% per change.', round(abs(v_new - v_old) / v_old * 100, 1), s.max_budget_change_pct);
    end if;
  elsif p_type = 'TARGET_BID' then
    v_new := (p_new ->> 'bid')::numeric; v_old := (p_old ->> 'bid')::numeric;
    if v_new is null or v_new < 0.01 then return 'The new bid must be at least 0.01.'; end if;
    if s.max_bid is not null and v_new > s.max_bid then return format('The bid %s exceeds the configured maximum bid of %s.', v_new, s.max_bid); end if;
    if v_old > 0 and abs(v_new - v_old) / v_old * 100 > s.max_bid_change_pct then
      return format('The change of %s%% is larger than the allowed %s%% per change.', round(abs(v_new - v_old) / v_old * 100, 1), s.max_bid_change_pct);
    end if;
  elsif p_type in ('CAMPAIGN_STATE', 'TARGET_STATE') then
    if p_new ->> 'state' not in ('ENABLED', 'PAUSED') then return 'The new state must be ENABLED or PAUSED.'; end if;
    if p_new ->> 'state' = p_old ->> 'state' then return 'The new state is the same as the current state.'; end if;
  elsif p_type = 'NEGATIVE_KEYWORD' then
    if length(btrim(coalesce(p_new ->> 'keyword', ''))) not between 1 and 80 then return 'Enter the negative keyword (1-80 characters).'; end if;
    if p_new ->> 'match_type' not in ('NEGATIVE_EXACT', 'NEGATIVE_PHRASE') then return 'Negative match type must be NEGATIVE_EXACT or NEGATIVE_PHRASE.'; end if;
  end if;
  return null;
end $$;

-- The current value is always read from the latest synchronised snapshot on the server, never from the client.
create or replace function private.amazon_current_value(p_company uuid, p_type text, p_campaign text, p_target text)
returns jsonb language sql stable security definer set search_path = '' as $$
  select case
    when p_type = 'CAMPAIGN_BUDGET' then (select jsonb_build_object('daily_budget', c.daily_budget, 'campaign_id', c.campaign_id) from public.amazon_campaigns c where c.company_id = p_company and c.campaign_id = p_campaign limit 1)
    when p_type = 'CAMPAIGN_STATE' then (select jsonb_build_object('state', c.state) from public.amazon_campaigns c where c.company_id = p_company and c.campaign_id = p_campaign limit 1)
    when p_type = 'TARGET_BID' then (select jsonb_build_object('bid', t.bid) from public.amazon_targets t where t.company_id = p_company and t.target_id = p_target and t.campaign_id = p_campaign limit 1)
    when p_type = 'TARGET_STATE' then (select jsonb_build_object('state', t.state) from public.amazon_targets t where t.company_id = p_company and t.target_id = p_target and t.campaign_id = p_campaign limit 1)
    when p_type = 'NEGATIVE_KEYWORD' then jsonb_build_object('negative', false)
  end
$$;

create or replace function public.amazon_ad_change_request(p_change jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_company uuid := private.require_permission('amazon_ads.request');
  v_type text := p_change ->> 'change_type';
  v_campaign public.amazon_campaigns;
  v_target public.amazon_targets;
  v_old jsonb;
  v_new jsonb;
  v_problem text;
  v_id uuid;
  v_label text;
begin
  if v_type not in ('CAMPAIGN_BUDGET', 'CAMPAIGN_STATE', 'TARGET_BID', 'TARGET_STATE', 'NEGATIVE_KEYWORD') then raise exception 'Unknown change type.' using errcode = 'P0001'; end if;
  select * into v_campaign from public.amazon_campaigns where company_id = v_company and campaign_id = p_change ->> 'campaign_id' limit 1;
  if not found then raise exception 'Campaign not found in your company.' using errcode = 'P0001'; end if;
  if v_type in ('TARGET_BID', 'TARGET_STATE') then
    select * into v_target from public.amazon_targets where company_id = v_company and target_id = p_change ->> 'target_id' and campaign_id = v_campaign.campaign_id limit 1;
    if not found then raise exception 'Target not found in this campaign.' using errcode = 'P0001'; end if;
  end if;
  v_old := private.amazon_current_value(v_company, v_type, v_campaign.campaign_id, v_target.target_id);
  if v_old is null or (v_type = 'CAMPAIGN_BUDGET' and v_old ->> 'daily_budget' is null) or (v_type = 'TARGET_BID' and v_old ->> 'bid' is null) then
    raise exception 'The current value is not known yet. Synchronise the campaign first.' using errcode = 'P0001';
  end if;
  v_new := case v_type
    when 'CAMPAIGN_BUDGET' then jsonb_build_object('daily_budget', round((p_change ->> 'daily_budget')::numeric, 2), 'campaign_id', v_campaign.campaign_id)
    when 'TARGET_BID' then jsonb_build_object('bid', round((p_change ->> 'bid')::numeric, 2))
    when 'NEGATIVE_KEYWORD' then jsonb_build_object('keyword', lower(btrim(p_change ->> 'keyword')), 'match_type', coalesce(p_change ->> 'match_type', 'NEGATIVE_EXACT'),
      'ad_group_id', nullif(p_change ->> 'ad_group_id', ''))
    else jsonb_build_object('state', upper(p_change ->> 'state')) end;
  v_problem := private.amazon_change_problem(v_company, v_type, v_old, v_new);
  if v_problem is not null then raise exception '%', v_problem using errcode = 'P0001'; end if;
  v_label := v_campaign.name || coalesce(' / ' || v_target.expression, '') || coalesce(' / negative "' || (v_new ->> 'keyword') || '"', '');
  insert into public.amazon_ad_change_requests (company_id, change_type, profile_id, campaign_id, ad_group_id, target_id, entity_label, old_value, proposed_value, reason,
    expected_impact, recommendation_id, requested_by, is_demo, rollback_instructions)
  values (v_company, v_type, v_campaign.profile_id, v_campaign.campaign_id, coalesce(v_target.ad_group_id, nullif(p_change ->> 'ad_group_id', '')), v_target.target_id, left(v_label, 600),
    v_old, v_new, btrim(p_change ->> 'reason'), nullif(btrim(p_change ->> 'expected_impact'), ''), nullif(p_change ->> 'recommendation_id', '')::uuid, auth.uid(), v_campaign.is_demo,
    case v_type when 'CAMPAIGN_BUDGET' then format('Restore the daily budget to %s with a new change request.', v_old ->> 'daily_budget')
      when 'TARGET_BID' then format('Restore the bid to %s with a new change request.', v_old ->> 'bid')
      when 'NEGATIVE_KEYWORD' then 'Archive the negative keyword in Amazon Ads (negative keywords cannot be re-enabled once archived).'
      else format('Set the state back to %s with a new change request.', v_old ->> 'state') end)
  returning id into v_id;
  perform private.write_audit_log(v_company, 'amazon.ad_change_requested', 'amazon_ad_change', v_id::text,
    jsonb_build_object('module', 'amazon', 'result', 'success', 'type', v_type, 'old', v_old, 'proposed', v_new, 'demo', v_campaign.is_demo));
  perform private.notify_permission(v_company, 'amazon_ads.approve', 'APPROVAL_REQUESTED', 'Amazon ad change awaiting approval',
    left(format('%s: %s -> %s. %s', v_label, v_old, v_new, btrim(p_change ->> 'reason')), 500), 'MEDIUM', 'AMAZON_AD_CHANGE', v_id::text, '/amazon/recommendations?tab=changes', 'amazon-change:' || v_id, auth.uid());
  return jsonb_build_object('id', v_id, 'status', 'PENDING_APPROVAL');
exception when unique_violation then
  raise exception 'An open change request already exists for this item.' using errcode = 'P0001';
end $$;

create or replace function public.amazon_ad_change_decide(p_id uuid, p_decision text, p_note text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_company uuid := private.require_permission('amazon_ads.approve');
  v_r public.amazon_ad_change_requests;
  v_current jsonb;
  v_problem text;
begin
  select * into v_r from public.amazon_ad_change_requests where id = p_id and company_id = v_company for update;
  if not found then raise exception 'Change request not found.' using errcode = 'P0001'; end if;
  if v_r.status <> 'PENDING_APPROVAL' then raise exception 'This request is already %.', lower(v_r.status) using errcode = 'P0001'; end if;
  if v_r.requested_by = auth.uid() then raise exception 'Segregation of duties: you cannot approve your own change request.' using errcode = '42501'; end if;
  if p_decision = 'REJECT' then
    if length(btrim(coalesce(p_note, ''))) < 3 then raise exception 'Give a reason for rejecting.' using errcode = 'P0001'; end if;
    update public.amazon_ad_change_requests set status = 'REJECTED', decided_by = auth.uid(), decided_at = now(), decision_note = btrim(p_note), updated_at = now() where id = p_id;
  elsif p_decision = 'APPROVE' then
    v_current := private.amazon_current_value(v_company, v_r.change_type, v_r.campaign_id, v_r.target_id);
    if v_r.change_type <> 'NEGATIVE_KEYWORD' and v_current is distinct from v_r.old_value then
      update public.amazon_ad_change_requests set status = 'CANCELLED', decided_by = auth.uid(), decided_at = now(),
        decision_note = 'Cancelled at approval: the current value changed since the request was made.', updated_at = now() where id = p_id;
      perform private.write_audit_log(v_company, 'amazon.ad_change_cancelled_stale', 'amazon_ad_change', p_id::text, jsonb_build_object('module', 'amazon', 'result', 'failure'));
      return jsonb_build_object('id', p_id, 'status', 'CANCELLED', 'stale', true);
    end if;
    v_problem := private.amazon_change_problem(v_company, v_r.change_type, v_r.old_value, v_r.proposed_value);
    if v_problem is not null then raise exception 'Cannot approve: %', v_problem using errcode = 'P0001'; end if;
    update public.amazon_ad_change_requests set status = 'APPROVED', decided_by = auth.uid(), decided_at = now(), decision_note = nullif(btrim(p_note), ''), updated_at = now() where id = p_id;
  else
    raise exception 'Decision must be APPROVE or REJECT.' using errcode = 'P0001';
  end if;
  perform private.write_audit_log(v_company, 'amazon.ad_change_' || lower(p_decision) || 'd', 'amazon_ad_change', p_id::text,
    jsonb_build_object('module', 'amazon', 'result', 'success', 'type', v_r.change_type, 'old', v_r.old_value, 'proposed', v_r.proposed_value, 'note', p_note));
  perform private.notify(v_company, v_r.requested_by, case when p_decision = 'APPROVE' then 'APPROVAL_APPROVED' else 'APPROVAL_REJECTED' end,
    case when p_decision = 'APPROVE' then 'Amazon ad change approved' else 'Amazon ad change rejected' end, left(v_r.entity_label, 300), 'INFO', 'AMAZON_AD_CHANGE', p_id::text,
    '/amazon/recommendations?tab=changes', 'amazon-change-decided:' || p_id);
  return jsonb_build_object('id', p_id, 'status', case when p_decision = 'APPROVE' then 'APPROVED' else 'REJECTED' end);
end $$;

create or replace function public.amazon_ad_change_cancel(p_id uuid, p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_company uuid := private.require_any_permission(array['amazon_ads.request', 'amazon_ads.approve']); v_r public.amazon_ad_change_requests;
begin
  select * into v_r from public.amazon_ad_change_requests where id = p_id and company_id = v_company for update;
  if not found then raise exception 'Change request not found.' using errcode = 'P0001'; end if;
  if v_r.status not in ('PENDING_APPROVAL', 'APPROVED') then raise exception 'Only pending or approved (not yet executed) requests can be cancelled.' using errcode = 'P0001'; end if;
  if v_r.requested_by <> auth.uid() and not private.has_permission(v_company, 'amazon_ads.approve') then raise exception 'Only the requester or an approver can cancel.' using errcode = '42501'; end if;
  update public.amazon_ad_change_requests set status = 'CANCELLED', decision_note = left(btrim(p_reason), 1000), updated_at = now() where id = p_id;
  perform private.write_audit_log(v_company, 'amazon.ad_change_cancelled', 'amazon_ad_change', p_id::text, jsonb_build_object('module', 'amazon', 'result', 'success', 'reason', p_reason));
