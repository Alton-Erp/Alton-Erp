-- Execution claim (service role only, called by the amazon-ads Edge Function after it authenticated the caller).
create or replace function public.amazon_service_change_claim(p_company uuid, p_id uuid, p_executor uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_r public.amazon_ad_change_requests; v_s public.amazon_settings; v_conn public.amazon_connections; v_problem text;
begin
  select * into v_s from public.amazon_settings where company_id = p_company;
  select * into v_conn from public.amazon_connections where company_id = p_company and api = 'ADS_API';
  select * into v_r from public.amazon_ad_change_requests where id = p_id and company_id = p_company for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'Change request not found.'); end if;
  if v_r.status <> 'APPROVED' then return jsonb_build_object('ok', false, 'reason', format('The request is %s, not approved.', lower(v_r.status))); end if;
  if v_r.is_demo then return jsonb_build_object('ok', false, 'reason', 'Demo changes are never sent to Amazon.'); end if;
  if v_s.automation_mode <> 'APPROVAL_REQUIRED' then return jsonb_build_object('ok', false, 'reason', 'Automation is in READ-ONLY mode. An approver must switch it to "approval required" first.'); end if;
  if v_s.kill_switch then return jsonb_build_object('ok', false, 'reason', 'The kill switch is ON: no change can be sent to Amazon.'); end if;
  if v_conn.status <> 'CONNECTED' then return jsonb_build_object('ok', false, 'reason', 'The Amazon Ads API is not connected.'); end if;
  v_problem := private.amazon_change_problem(p_company, v_r.change_type, v_r.old_value, v_r.proposed_value);
  if v_problem is not null then return jsonb_build_object('ok', false, 'reason', v_problem); end if;
  if v_r.change_type <> 'NEGATIVE_KEYWORD' and private.amazon_current_value(p_company, v_r.change_type, v_r.campaign_id, v_r.target_id) is distinct from v_r.old_value then
    update public.amazon_ad_change_requests set status = 'CANCELLED', decision_note = 'Cancelled before execution: the current value changed.', updated_at = now() where id = p_id;
    return jsonb_build_object('ok', false, 'reason', 'The current value changed since approval; the request was cancelled.');
  end if;
  update public.amazon_ad_change_requests set status = 'EXECUTING', executed_by = p_executor, updated_at = now() where id = p_id returning * into v_r;
  return jsonb_build_object('ok', true, 'request', to_jsonb(v_r));
end $$;

create or replace function public.amazon_service_change_result(p_company uuid, p_id uuid, p_success boolean, p_request_id text, p_response jsonb, p_error text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_r public.amazon_ad_change_requests;
begin
  update public.amazon_ad_change_requests set status = case when p_success then 'SUCCEEDED' else 'FAILED' end, executed_at = now(), api_request_id = left(p_request_id, 200),
    api_response = p_response, error_message = left(private.redact(p_error), 2000), updated_at = now()
  where id = p_id and company_id = p_company and status = 'EXECUTING' returning * into v_r;
  if not found then return jsonb_build_object('ok', false, 'reason', 'Request is not executing.'); end if;
  if p_success then
    -- Record the confirmed value in the local snapshot until the next sync.
    if v_r.change_type = 'CAMPAIGN_BUDGET' then update public.amazon_campaigns set daily_budget = (v_r.proposed_value ->> 'daily_budget')::numeric, updated_at = now() where company_id = p_company and campaign_id = v_r.campaign_id;
    elsif v_r.change_type = 'CAMPAIGN_STATE' then update public.amazon_campaigns set state = v_r.proposed_value ->> 'state', updated_at = now() where company_id = p_company and campaign_id = v_r.campaign_id;
    elsif v_r.change_type = 'TARGET_BID' then update public.amazon_targets set bid = (v_r.proposed_value ->> 'bid')::numeric where company_id = p_company and target_id = v_r.target_id;
    elsif v_r.change_type = 'TARGET_STATE' then update public.amazon_targets set state = v_r.proposed_value ->> 'state' where company_id = p_company and target_id = v_r.target_id;
    end if;
    update public.amazon_recommendations set status = 'EXECUTED', updated_at = now() where id = v_r.recommendation_id and company_id = p_company;
  end if;
  perform private.write_audit_log(p_company, 'amazon.ad_change_' || case when p_success then 'executed' else 'failed' end, 'amazon_ad_change', p_id::text,
    jsonb_build_object('module', 'amazon', 'result', case when p_success then 'success' else 'failure' end, 'type', v_r.change_type, 'old', v_r.old_value,
      'proposed', v_r.proposed_value, 'api_request_id', p_request_id, 'error', left(private.redact(p_error), 300)));
  perform private.notify(p_company, v_r.requested_by, 'AMAZON_AD_CHANGE_RESULT', case when p_success then 'Amazon ad change applied' else 'Amazon ad change FAILED' end,
    left(v_r.entity_label || coalesce(': ' || private.redact(p_error), ''), 400), case when p_success then 'INFO' else 'HIGH' end, 'AMAZON_AD_CHANGE', p_id::text,
    '/amazon/recommendations?tab=changes', 'amazon-change-result:' || p_id);
  return jsonb_build_object('ok', true, 'status', v_r.status);
end $$;

