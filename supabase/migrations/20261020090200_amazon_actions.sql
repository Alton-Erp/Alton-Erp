-- =============================================================================
-- Amazon: recommendations, budget plans, approval-based ad changes, demo data
--
-- Ad changes: READ-ONLY by default (automation_mode = READ_ONLY, kill switch
-- ON). A change is proposed (amazon_ads.request), approved by a different
-- person (amazon_ads.approve) after the limits are re-checked, and executed
-- only by the amazon-ads Edge Function through a supported Amazon Ads API call.
-- A change is SUCCEEDED only when the API response confirms it.
--
-- Demo data: separate rows flagged is_demo / data_source DEMO, never mapped to
-- ERP products, never read by live analytics, removable in one step.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Recommendations (rule-based; generated by the shared engine, stored here)
-- -----------------------------------------------------------------------------
create table if not exists public.amazon_recommendations (
  id               uuid primary key default gen_random_uuid(),
  company_id       uuid not null references public.companies (id) on delete restrict,
  rule_code        text not null check (rule_code ~ '^[A-Z_]{3,60}$'),
  entity_type      text not null check (entity_type in ('PRODUCT', 'CAMPAIGN', 'TARGET', 'SEARCH_TERM', 'ACCOUNT')),
  entity_key       text not null check (length(entity_key) between 1 and 600),
  entity_label     text not null check (length(entity_label) between 1 and 600),
  period_from      date not null,
  period_to        date not null,
  title            text not null check (length(title) between 3 and 300),
  issue            text not null check (length(issue) <= 2000),
  proposed_action  text not null check (length(proposed_action) <= 2000),
  evidence         jsonb not null default '{}'::jsonb,
  financial        jsonb not null default '{}'::jsonb,
  impact_direction text not null check (impact_direction in ('INCREASE_CONTRIBUTION', 'REDUCE_WASTE', 'PROTECT_STOCK', 'GROW_SALES', 'IMPROVE_DATA', 'NONE')),
  confidence       text not null check (confidence in ('LOW', 'MEDIUM', 'HIGH')),
  missing_info     text[] not null default '{}',
  inventory_impact text check (inventory_impact is null or length(inventory_impact) <= 1000),
  priority         numeric(14,2) not null default 0,
  status           text not null default 'OPEN' check (status in ('OPEN', 'ACCEPTED', 'DISMISSED', 'EXECUTED', 'SUPERSEDED')),
  status_note      text check (status_note is null or length(status_note) <= 1000),
  outcome          jsonb,
  is_demo          boolean not null default false,
  created_by       uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint amazon_recommendations_unique unique (company_id, is_demo, rule_code, entity_key, period_to)
);
create index if not exists amazon_recommendations_company_idx on public.amazon_recommendations (company_id, is_demo, status, priority desc);

create table if not exists public.amazon_budget_plans (
  id            uuid primary key default gen_random_uuid(),
  company_id    uuid not null references public.companies (id) on delete restrict,
  name          text not null check (length(btrim(name)) between 3 and 120),
  month         date not null,
  inputs        jsonb not null,
  allocation    jsonb not null,
  assumptions   text[] not null default '{}',
  is_demo       boolean not null default false,
  created_by    uuid,
  created_at    timestamptz not null default now()
);
create index if not exists amazon_budget_plans_company_idx on public.amazon_budget_plans (company_id, created_at desc);

create table if not exists public.amazon_ad_change_requests (
  id                    uuid primary key default gen_random_uuid(),
  company_id            uuid not null references public.companies (id) on delete restrict,
  change_type           text not null check (change_type in ('CAMPAIGN_BUDGET', 'CAMPAIGN_STATE', 'TARGET_BID', 'TARGET_STATE', 'NEGATIVE_KEYWORD')),
  profile_id            text not null,
  campaign_id           text not null,
  ad_group_id           text,
  target_id             text,
  entity_label          text not null check (length(entity_label) <= 600),
  old_value             jsonb not null,
  proposed_value        jsonb not null,
  reason                text not null check (length(btrim(reason)) between 5 and 2000),
  expected_impact       text check (expected_impact is null or length(expected_impact) <= 2000),
  recommendation_id     uuid references public.amazon_recommendations (id) on delete set null,
  status                text not null default 'PENDING_APPROVAL' check (status in ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'CANCELLED', 'EXECUTING', 'SUCCEEDED', 'FAILED')),
  requested_by          uuid not null,
  requested_at          timestamptz not null default now(),
  decided_by            uuid,
  decided_at            timestamptz,
  decision_note         text check (decision_note is null or length(decision_note) <= 1000),
  executed_by           uuid,
  executed_at           timestamptz,
  api_request_id        text check (api_request_id is null or length(api_request_id) <= 200),
  api_response          jsonb,
  error_message         text check (error_message is null or length(error_message) <= 2000),
  rollback_instructions text check (rollback_instructions is null or length(rollback_instructions) <= 1000),
  is_demo               boolean not null default false,
  updated_at            timestamptz not null default now()
);
create index if not exists amazon_ad_change_requests_company_idx on public.amazon_ad_change_requests (company_id, status, requested_at desc);
create unique index if not exists amazon_ad_change_one_open on public.amazon_ad_change_requests (company_id, change_type, campaign_id, coalesce(target_id, ''), coalesce(proposed_value ->> 'keyword', ''))
  where status in ('PENDING_APPROVAL', 'APPROVED', 'EXECUTING');

do $$
declare t text;
begin
  foreach t in array array['amazon_recommendations', 'amazon_budget_plans', 'amazon_ad_change_requests'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
    execute format('grant select on table public.%I to authenticated', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (company_id = (select private.current_company_id()) and (select private.amazon_can(private.current_company_id(), ''amazon.read'')))', t || '_select', t);
  end loop;
end $$;

-- Save the engine's recommendations: upsert on (rule, entity, period end); open
-- recommendations of earlier periods for the same rule and entity are superseded.
create or replace function public.amazon_recommendations_save(p_items jsonb, p_demo boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_company uuid := private.require_permission('amazon.manage');
  v_item jsonb;
  v_saved int := 0;
  v_superseded int := 0;
  v_n int;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) > 1000 then
    raise exception 'Provide at most 1,000 recommendations.' using errcode = 'P0001';
  end if;
  for v_item in select value from jsonb_array_elements(p_items) loop
    insert into public.amazon_recommendations as r (company_id, rule_code, entity_type, entity_key, entity_label, period_from, period_to, title, issue, proposed_action,
      evidence, financial, impact_direction, confidence, missing_info, inventory_impact, priority, is_demo, created_by)
    values (v_company, v_item ->> 'rule_code', v_item ->> 'entity_type', left(v_item ->> 'entity_key', 600), left(v_item ->> 'entity_label', 600),
      (v_item ->> 'period_from')::date, (v_item ->> 'period_to')::date, left(v_item ->> 'title', 300), left(v_item ->> 'issue', 2000), left(v_item ->> 'proposed_action', 2000),
      coalesce(v_item -> 'evidence', '{}'::jsonb), coalesce(v_item -> 'financial', '{}'::jsonb), v_item ->> 'impact_direction', v_item ->> 'confidence',
      coalesce(array(select jsonb_array_elements_text(v_item -> 'missing_info')), '{}'), left(v_item ->> 'inventory_impact', 1000),
      coalesce((v_item ->> 'priority')::numeric, 0), p_demo, auth.uid())
    on conflict (company_id, is_demo, rule_code, entity_key, period_to) do update set
      title = excluded.title, issue = excluded.issue, proposed_action = excluded.proposed_action, evidence = excluded.evidence, financial = excluded.financial,
      impact_direction = excluded.impact_direction, confidence = excluded.confidence, missing_info = excluded.missing_info, inventory_impact = excluded.inventory_impact,
      priority = excluded.priority, updated_at = now()
    where r.status = 'OPEN';
    update public.amazon_recommendations set status = 'SUPERSEDED', status_note = 'Replaced by the analysis of a later period.', updated_at = now()
    where company_id = v_company and is_demo = p_demo and rule_code = v_item ->> 'rule_code' and entity_key = left(v_item ->> 'entity_key', 600)
      and period_to < (v_item ->> 'period_to')::date and status = 'OPEN';
    get diagnostics v_n = row_count;
    v_superseded := v_superseded + v_n;
    v_saved := v_saved + 1;
  end loop;
  perform private.write_audit_log(v_company, 'amazon.recommendations_generated', 'amazon_recommendation', null,
    jsonb_build_object('module', 'amazon', 'result', 'success', 'count', v_saved, 'superseded', v_superseded, 'demo', p_demo));
  return jsonb_build_object('saved', v_saved, 'superseded', v_superseded);
end $$;

create or replace function public.amazon_recommendation_set_status(p_id uuid, p_status text, p_note text default null, p_outcome jsonb default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_company uuid := private.require_permission('amazon.manage'); v_r public.amazon_recommendations;
begin
  if p_status not in ('OPEN', 'ACCEPTED', 'DISMISSED', 'EXECUTED') then raise exception 'Unknown status.' using errcode = 'P0001'; end if;
  if p_status = 'DISMISSED' and length(btrim(coalesce(p_note, ''))) < 3 then raise exception 'Give a reason for dismissing.' using errcode = 'P0001'; end if;
  update public.amazon_recommendations set status = p_status, status_note = coalesce(nullif(btrim(p_note), ''), status_note),
    outcome = coalesce(p_outcome, outcome), updated_at = now()
  where id = p_id and company_id = v_company returning * into v_r;
  if not found then raise exception 'Recommendation not found.' using errcode = 'P0001'; end if;
  perform private.write_audit_log(v_company, 'amazon.recommendation_' || lower(p_status), 'amazon_recommendation', p_id::text,
    jsonb_build_object('module', 'amazon', 'result', 'success', 'rule', v_r.rule_code, 'entity', v_r.entity_label, 'note', p_note));
  return jsonb_build_object('id', v_r.id, 'status', v_r.status);
end $$;

