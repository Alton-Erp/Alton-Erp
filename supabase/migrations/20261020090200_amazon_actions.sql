-- Removes ONLY demo rows of the caller's company. Live and ERP data are untouched.
create or replace function public.amazon_demo_clear()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_company uuid := private.require_permission('amazon.manage'); v_n bigint := 0; v_k bigint; t text;
begin
  foreach t in array array['amazon_ad_change_requests', 'amazon_recommendations', 'amazon_budget_plans', 'amazon_search_term_daily', 'amazon_ad_product_daily', 'amazon_campaign_daily',
    'amazon_targets', 'amazon_ad_groups', 'amazon_campaigns', 'amazon_inventory_snapshots', 'amazon_sku_daily', 'amazon_listings'] loop
    execute format('delete from public.%I where company_id = $1 and is_demo', t) using v_company;
    get diagnostics v_k = row_count;
    v_n := v_n + v_k;
  end loop;
  delete from public.amazon_sync_jobs where company_id = v_company and api = 'DEMO';
  if v_n > 0 then
    perform private.write_audit_log(v_company, 'amazon.demo_cleared', 'amazon_settings', v_company::text, jsonb_build_object('module', 'amazon', 'result', 'success', 'rows', v_n));
  end if;
  return jsonb_build_object('deleted', v_n);
end $$;

