// Column definitions for the customer PO exports. Identifiers (SKUs, PO
// numbers, codes) are exported as text so Excel keeps leading zeros.
import { AVAILABILITY_LABELS, LINE_STATUS_LABELS, MATCH_METHOD_LABELS, PO_STATUS_LABELS, STATUS_REASON_LABELS, STRATEGY_LABELS } from './po-import.ts'
import type { ExportColumn } from './export-utils'
import type { AnalysisLine, ShortageRow } from '@/services/customer-po'
import type { CustomerPoLineListRow, CustomerPoListRow, PoAllocationListRow, PoAllocationRunRow, PoEventRow } from '@/types/database-customer-po'

const n = (v: number | string | null | undefined) => (v === null || v === undefined ? null : Number(v))

export const LINE_DETAIL_EXPORT: ExportColumn<CustomerPoLineListRow>[] = [
  { header: 'PO reference', value: (l) => l.po_reference },
  { header: 'Customer PO number', value: (l) => l.customer_po_number },
  { header: 'Revision', value: (l) => l.revision },
  { header: 'Customer', value: (l) => l.customer_name_snapshot },
  { header: 'Line', value: (l) => l.line_no },
  { header: 'File row', value: (l) => l.source_row_number },
  { header: 'Uploaded SKU', value: (l) => l.uploaded_sku },
  { header: 'Customer SKU', value: (l) => l.uploaded_customer_sku },
  { header: 'Barcode', value: (l) => l.uploaded_barcode },
  { header: 'Uploaded description', value: (l) => l.uploaded_description },
  { header: 'Uploaded quantity', value: (l) => n(l.uploaded_quantity) },
  { header: 'Uploaded unit', value: (l) => l.uploaded_unit },
  { header: 'Quantity ordered', value: (l) => n(l.quantity_ordered) },
  { header: 'Unit', value: (l) => l.unit },
  { header: 'Unit price', value: (l) => n(l.unit_price) },
  { header: 'Currency', value: (l) => l.currency },
  { header: 'Tax rate', value: (l) => n(l.tax_rate) },
  { header: 'HSN', value: (l) => l.hsn_code },
  { header: 'Remarks', value: (l) => l.remarks },
  { header: 'Line status', value: (l) => LINE_STATUS_LABELS[l.line_status] },
  { header: 'Matched SKU', value: (l) => l.sku },
  { header: 'Product name', value: (l) => l.product_name },
  { header: 'Allocated (open)', value: (l) => n(l.allocated_open) },
  { header: 'Dispatched', value: (l) => n(l.quantity_dispatched) },
]

