export type SupplierCategory = 'RAW_MATERIAL' | 'FINISHED_GOODS' | 'PACKAGING' | 'MACHINERY' | 'SERVICES' | 'OTHER'
export type SupplierPaymentTerms = 'IMMEDIATE' | 'DAYS_7' | 'DAYS_15' | 'DAYS_30' | 'DAYS_45' | 'CUSTOM'
export type SupplierStatus = 'ACTIVE' | 'INACTIVE'

export type SupplierRow = {
  id: string
  company_id: string
  supplier_code: string
  legal_name: string
  display_name: string | null
  category: SupplierCategory
  contact_person: string | null
  phone: string | null
  alternate_phone: string | null
  email: string | null
  gstin: string | null
  pan: string | null
  billing_address: string | null
  shipping_address: string | null
  city: string | null
  state_code: string | null
  pin_code: string | null
  country: string
  payment_terms: SupplierPaymentTerms
  custom_payment_days: number | null
  notes: string | null
  status: SupplierStatus
  created_by: string | null
  updated_by: string | null
  created_at: string
  updated_at: string
}

/** Columns clients may update (company_id and supplier_code are fixed after creation). */
export type SupplierUpdate = Partial<Omit<SupplierRow, 'id' | 'company_id' | 'supplier_code' | 'created_by' | 'updated_by' | 'created_at' | 'updated_at'>>

/** Insert payload: supplier_code omitted or null = generated by the database (SUP-000001). */
export type SupplierInsert = SupplierUpdate & { company_id: string; legal_name: string; supplier_code?: string | null }

export type SupplierActivityRow = {
  id: string
  action: string
  event_timestamp: string
  actor_name: string | null
  metadata: { supplier_code?: string; legal_name?: string; changed_fields?: string[]; from?: string; to?: string } | null
}

export type SupplierTables = {
  suppliers: {
    Row: SupplierRow
    Insert: SupplierInsert
    Update: SupplierUpdate
    Relationships: []
  }
}

export type SupplierFunctions = {
  supplier_activity: {
    Args: { p_supplier_id: string }
    Returns: SupplierActivityRow[]
  }
}
